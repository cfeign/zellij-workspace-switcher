#!/usr/bin/env bash
# Generates a Zellij layout from ~/.config/zellij/projects.json.
#
#   generate-layout.sh [6|8]      default: "grid" from projects.json, else 8
#
# Output: ~/.config/zellij/layouts/workspace-<N>.kdl
#
# The layout opens one floating pane per type (claude, git, issues, test, adhoc)
# for every slot, named by the convention the plugin parses (claude-3-myproj,
# git-3, ...). It also passes the resolved pane commands to the plugin so a live
# swap (Alt+s) opens the same commands. All paths are resolved here, at
# generation time, so nothing machine-specific is hardcoded anywhere.
set -euo pipefail

PROJECTS_JSON="${WORKSPACE_PROJECTS_JSON:-$HOME/.config/zellij/projects.json}"
LAYOUT_DIR="$HOME/.config/zellij/layouts"
PLUGIN="file:~/.config/zellij/plugins/workspace_switcher.wasm"

if [[ ! -f "$PROJECTS_JSON" ]]; then
    echo "Error: $PROJECTS_JSON not found (copy config/projects.json.example there)" >&2
    exit 1
fi
command -v jq >/dev/null || { echo "Error: jq is required" >&2; exit 1; }

GRID_SIZE="${1:-$(jq -r '.grid // 8' "$PROJECTS_JSON")}"
if [[ "$GRID_SIZE" != "6" && "$GRID_SIZE" != "8" ]]; then
    echo "Error: grid size must be 6 or 8 (got: $GRID_SIZE)" >&2
    exit 1
fi

OUTPUT_FILE="$LAYOUT_DIR/workspace-$GRID_SIZE.kdl"
mkdir -p "$LAYOUT_DIR"

# Grid cell positions for the claude panes (percent of screen)
if [[ "$GRID_SIZE" == "6" ]]; then
    X_PCT=(0 33 67 0 33 67); Y_PCT=(0 0 0 50 50 50); W_PCT=(33 34 33 33 34 33)
else
    X_PCT=(0 25 50 75 0 25 50 75); Y_PCT=(0 0 0 0 50 50 50 50); W_PCT=(25 25 25 25 25 25 25 25)
fi

# --- Resolve pane commands ---------------------------------------------------
# projects.json "panes" maps each tool pane to a command name or path.
# Empty / missing = the shell. Everything is resolved to an absolute path.
expand_tilde() { printf '%s' "${1/#\~/$HOME}"; }

# This script may be run through a symlink; find the repo so bare names like
# "claude-workspace" resolve to scripts/ even before setup.sh has linked them.
SELF="${BASH_SOURCE[0]}"; while [[ -L "$SELF" ]]; do SELF="$(readlink "$SELF")"; done
SCRIPTS_DIR="$(cd "$(dirname "$SELF")" && pwd)"
export PATH="/opt/homebrew/bin:/usr/local/bin:$HOME/.local/bin:$PATH"

resolve_cmd() {
    local raw; raw="$(expand_tilde "$1")"
    if [[ -z "$raw" ]]; then
        printf '%s' "$SHELL_CMD"
    elif [[ "$raw" == /* ]]; then
        printf '%s' "$raw"
    elif [[ -x "$SCRIPTS_DIR/$raw" ]]; then
        printf '%s' "$SCRIPTS_DIR/$raw"
    else
        command -v "$raw" || { echo "Error: command '$raw' from projects.json not found on PATH" >&2; exit 1; }
    fi
}

shell_pref="$(jq -r '.shell // ""' "$PROJECTS_JSON")"
if [[ -n "$shell_pref" ]]; then
    SHELL_CMD="$(resolve_cmd "$shell_pref")"
else
    SHELL_CMD="$(command -v fish || command -v zsh || command -v bash)"
fi

CLAUDE_CMD="$(resolve_cmd "$(jq -r '.panes.claude // "claude-workspace"' "$PROJECTS_JSON")")"
GIT_CMD="$(resolve_cmd "$(jq -r '.panes.git // ""' "$PROJECTS_JSON")")"
ISSUES_CMD="$(resolve_cmd "$(jq -r '.panes.issues // ""' "$PROJECTS_JSON")")"
TEST_CMD="$(resolve_cmd "$(jq -r '.panes.test // ""' "$PROJECTS_JSON")")"
ADHOC_CMD="$(resolve_cmd "$(jq -r '.panes.adhoc // ""' "$PROJECTS_JSON")")"

# --- Emit layout ---------------------------------------------------------------
{
cat <<HEADER
// Generated by zellij-workspace-switcher/scripts/generate-layout.sh $GRID_SIZE
// Do not hand-edit. Regenerate with: generate-layout.sh $GRID_SIZE

layout {
    tab name="workspace" focus=true hide_floating_panes=true {
        // The plugin pane: 1 row, borderless. The plugin repositions and
        // shows/hides the floating panes below; it renders nothing itself.
        pane size=1 borderless=true {
            plugin location="$PLUGIN" {
                claude_cmd "$CLAUDE_CMD"
                git_cmd "$GIT_CMD"
                issues_cmd "$ISSUES_CMD"
                test_cmd "$TEST_CMD"
                adhoc_cmd "$ADHOC_CMD"
            }
        }

        // A tab needs at least one tiled pane
        pane

        floating_panes {
HEADER

for slot in $(seq 1 "$GRID_SIZE"); do
    idx=$((slot - 1))
    x="${X_PCT[$idx]}"; y="${Y_PCT[$idx]}"; w="${W_PCT[$idx]}"

    project_name="$(jq -r --arg s "$slot" '.slots[$s] // empty' "$PROJECTS_JSON")"
    project_path=""
    if [[ -n "$project_name" ]]; then
        project_path="$(expand_tilde "$(jq -r --arg n "$project_name" '.projects[] | select(.name == $n) | .path' "$PROJECTS_JSON")")"
    fi

    if [[ -n "$project_path" ]]; then
        cwd_attr=" cwd=\"$project_path\""
    else
        project_name="empty"
        cwd_attr=""
    fi

    echo "            // Slot $slot: $project_name"
    cat <<PANE
            pane name="claude-${slot}-${project_name}"${cwd_attr} command="$CLAUDE_CMD" {
                x "${x}%"; y "${y}%"; width "${w}%"; height "50%"
            }
            pane name="git-${slot}"${cwd_attr} command="$GIT_CMD" {
                x "50%"; y "0%"; width "25%"; height "50%"
            }
            pane name="issues-${slot}"${cwd_attr} command="$ISSUES_CMD" {
                x "75%"; y "0%"; width "25%"; height "50%"
            }
            pane name="test-${slot}"${cwd_attr} command="$TEST_CMD" {
                x "50%"; y "50%"; width "25%"; height "50%"
            }
            pane name="adhoc-${slot}"${cwd_attr} command="$ADHOC_CMD" {
                x "75%"; y "50%"; width "25%"; height "50%"
            }

PANE
done

cat <<'FOOTER'
        }
    }
}
FOOTER
} > "$OUTPUT_FILE"

echo "Generated: $OUTPUT_FILE"
